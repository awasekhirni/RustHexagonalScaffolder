//! Domain layer codegen — per-table entity + native-PG-enum types.
//!
//! Emits `src/domain/entities/<table>.rs` for each table; the file contains
//! a `FromRow` entity struct (with serde + utoipa), a small `validate()`
//! stub that the application service calls before persistence, and the
//! native PG enum types referenced by the entity's columns.

use std::path::Path;

use anyhow::Result;
use heck::ToUpperCamelCase;

use crate::codegen::{write_file, ImportSet};
use crate::ir::{Schema, Table};

/// Writes `src/domain/entities/<table>.rs` for one table.
pub fn write_table(schema: &Schema, root: &Path, t: &Table) -> Result<()> {
    let path = root
        .join("src")
        .join("domain")
        .join("entities")
        .join(format!("{}.rs", t.module_name));
    write_file(&path, &entity_rs(schema, t))?;
    Ok(())
}

/// Writes `src/domain/mod.rs` and `src/domain/entities/mod.rs`.
pub fn write_mod(schema: &Schema, root: &Path) -> Result<()> {
    let mut body = String::from(
        "//! Domain entities — `FromRow` aggregate roots per bounded context.\n//!\n//! Each entity maps 1:1 to a PostgreSQL table via `sqlx::FromRow` and\n//! serialises to JSON for HTTP responses and the OpenAPI document.\n\n",
    );
    for t in &schema.tables {
        body.push_str(&format!("pub mod {};\n", t.module_name));
    }
    write_file(
        &root
            .join("src")
            .join("domain")
            .join("entities")
            .join("mod.rs"),
        &body,
    )?;

    let domain_mod = root.join("src").join("domain").join("mod.rs");
    write_file(
        &domain_mod,
        "//! Domain layer — pure business entities and value objects.\n//!\n//! This layer knows nothing about axum, SQLx or HTTP: it only declares\n//! *what* the application can do, never *how* it is done.\n\npub mod entities;\npub mod value_objects;\n",
    )?;

    let vo_dir = root.join("src").join("domain").join("value_objects");
    write_file(
        &vo_dir.join("mod.rs"),
        "//! Domain value objects — re-exports of the core value objects.\n\npub use crate::core::value_objects::email::Email;\npub use crate::core::value_objects::id::EntityId;\npub use crate::core::value_objects::money::Money;\n",
    )?;

    Ok(())
}

