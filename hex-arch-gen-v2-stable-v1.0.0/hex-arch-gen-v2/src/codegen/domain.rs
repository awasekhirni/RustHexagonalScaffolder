fn entity_rs(schema: &Schema, t: &Table) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "//! Domain entity for the `{}` table.\n//!\n//! Generated by `hex-gen` v2. Maps 1:1 to the PostgreSQL table via\n//! [`sqlx::FromRow`]; serialises to JSON for HTTP responses and the\n//! OpenAPI document (utoipa).\n\n",
        t.name
    ));

    let imports = ImportSet::from_cols(t.columns.iter());
    for line in imports.render() {
        out.push_str(&line);
        out.push('\n');
    }
    out.push_str("use serde::{Deserialize, Serialize};\n");
    out.push_str("use sqlx::FromRow;\n");
    out.push_str("use utoipa::ToSchema;\n");
    // v0.3.0 (closes G-C02): entities also derive `async_graphql::SimpleObject`
    // so they can be returned from GraphQL resolvers without a manual
    // `OutputType` impl. The `skip UNUSED_FIELDS` modifier keeps the
    // derive quiet about columns that have no GraphQL mapping.
    out.push_str("use async_graphql::SimpleObject;\n");

    out.push_str(&format!(
        "\n/// Aggregate root for `{}` records (PostgreSQL table `{}`).\n#[derive(Debug, Clone, Default, Serialize, Deserialize, FromRow, ToSchema, SimpleObject)]\npub struct {} {{\n",
        t.name, t.name, t.struct_name
    ));
    for c in &t.columns {
        let mut doc = c.doc_line();
        if let Some(fk) = t.foreign_keys.iter().find(|f| f.column == c.name) {
            doc.push_str(&format!(
                " References `{}({})`.",
                fk.ref_table, fk.ref_column
            ));
        }
        out.push_str(&format!("    /// {doc}\n"));
        if let Some(attr) = c.schema_attr() {
            out.push_str(&format!("    {attr}\n"));
        }
        for attr in c.rename_attrs() {
            out.push_str(&format!("    {attr}\n"));
        }
        out.push_str(&format!(
            "    pub {}: {},\n",
            c.field_ident,
            c.entity_type()
        ));
    }
    out.push_str("}\n\n");

    out.push_str(&format!(
        "impl {} {{\n    /// Placeholder for domain invariants; the application service\n    /// calls this before every write. Replace with real rules.\n    pub fn validate(&self) -> Result<(), String> {{\n        Ok(())\n    }}\n}}\n",
        t.struct_name
    ));

    // Native PG enums referenced by this table's columns.
    for (pg_name, rust_name) in t.used_enums() {
        let labels = schema.enums.get(&pg_name).cloned().unwrap_or_default();
        out.push_str(&enum_block(&pg_name, &rust_name, &labels));
    }

    out
}

/// Renders a single native PG enum definition.
fn enum_block(pg_name: &str, rust_name: &str, labels: &[String]) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "\n/// Native PostgreSQL enum `{pg_name}` (labels: {}).\n///\n/// v0.3.0 (closes G-C02): derives `async_graphql::Enum` so the enum\n/// can be returned from GraphQL resolvers without a manual `OutputType` impl.\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize, sqlx::Type, ToSchema, async_graphql::Enum)]\n#[sqlx(type_name = \"{pg_name}\", rename_all = \"snake_case\")]\n#[serde(rename_all = \"snake_case\")]\n#[graphql(rename_items = \"snake_case\")]\npub enum {rust_name} {{\n",
        labels.join(", ")
    ));
    for (idx, label) in labels.iter().enumerate() {
        out.push_str(&format!("    /// `{label}`\n"));
        if idx == 0 {
            out.push_str("    #[default]\n");
        }
        out.push_str(&format!("    {},\n", variant_ident(label)));
    }
    out.push_str("}\n\n");

    // FromStr impl so handlers can parse path segments into the enum.
    out.push_str(&format!(
        "impl std::str::FromStr for {rust_name} {{\n    type Err = String;\n\n    /// Parses a raw string (e.g. a path segment) into the enum.\n    fn from_str(raw: &str) -> Result<Self, Self::Err> {{\n        match raw {{\n"
    ));
    for label in labels {
        out.push_str(&format!(
            "            \"{label}\" => Ok(Self::{}),\n",
            variant_ident(label)
        ));
    }
    out.push_str(&format!(
        "            other => Err(format!(\"unknown {pg_name} value: {{other}}\")),\n        }}\n    }}\n}}\n"
    ));
    out
}

/// Rust variant identifier for a PG enum label.
fn variant_ident(label: &str) -> String {
    label.to_upper_camel_case().replace(['-', ' '], "_")
}
