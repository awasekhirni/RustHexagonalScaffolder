//! Wiring codegen — `src/lib.rs` and `src/main.rs` of the generated project.
//!
//! `lib.rs` re-exports the public modules; `main.rs` bootstraps logging +
//! settings, builds the pool, wires repositories → services → AppState,
//! merges Swagger UI, and serves with ordered graceful shutdown.

use std::path::Path;

use anyhow::Result;

use crate::codegen::write_file;
use crate::config::Config;
use crate::ir::Schema;

/// Writes `src/lib.rs` and `src/main.rs`.
pub fn write(schema: &Schema, root: &Path, cfg: &Config) -> Result<()> {
    write_file(&root.join("src").join("lib.rs"), &lib_rs(schema))?;
    write_file(&root.join("src").join("main.rs"), &main_rs(schema, cfg))?;
    Ok(())
}

fn lib_rs(_schema: &Schema) -> String {
    String::from(
        "//! Hexagonal REST + GraphQL API — library crate root.\n//!\n//! Re-exports the public modules composing the hexagonal architecture.\n//! v0.3.0 adds `graphql` (closes G-C02) alongside the existing REST\n//! surface; both share the same application service layer.\n\npub mod api;\npub mod application;\npub mod config;\npub mod core;\npub mod domain;\npub mod graphql;\npub mod infrastructure;\npub mod logging;\npub mod patterns;\npub mod presentation;\npub mod security;\npub mod shared;\npub mod telemetry;\n\n/// Re-export of the primary presentation entrypoint.\npub use presentation::build_router;\n",
    )
}

fn main_rs(schema: &Schema, cfg: &Config) -> String {
    let mut handler_imports = String::new();
    let mut wiring = String::new();
    let mut state_fields = String::new();

    for t in &schema.tables {
        let m = &t.module_name;
        let n = &t.struct_name;

        handler_imports.push_str(&format!(
            "use crate::application::services::{m}_service::{n}Service;\nuse crate::application::ports::repository::{n}ServicePort;\nuse crate::infrastructure::persistence::{m}_repository::Postgres{n}Repository;\n"
        ));

        wiring.push_str(&format!(
            "\n    // ── {m} context ────────────────────────────────────────────────────\n    let {m}_repo: std::sync::Arc<dyn crate::application::ports::repository::{n}Repository> =\n        std::sync::Arc::new(Postgres{n}Repository::new(pool.clone()));\n    let {m}_service: std::sync::Arc<dyn {n}ServicePort> =\n        std::sync::Arc::new({n}Service::new({m}_repo));\n"
        ));

        state_fields.push_str(&format!("            {m}_service: {m}_service.clone(),\n"));
    }

    format!(
        r#"//! Bootstraps the generated hexagonal REST API (v2).
//!
//! Wiring direction (hexagonal rules):
//!   HTTP handlers → AppState.services → repository ports → SQLx adapters
//!
//! Generated by `hex-gen` v2 — edit the generator templates rather than
//! this file.

mod api;
mod application;
mod config;
mod core;
mod domain;
mod graphql;
mod infrastructure;
mod logging;
mod patterns;
mod presentation;
mod security;
mod shared;
mod telemetry;

use std::sync::Arc;

use anyhow::Result;
use sqlx::PgPool;
use tracing::{{info, warn}};
use utoipa::OpenApi;
use utoipa_swagger_ui::SwaggerUi;

use crate::api::openapi::ApiDoc;
use crate::application::ports::bus::EventBus;
use crate::config::Settings;
use crate::core::shutdown::{{InFlightTracker, ShutdownCoordinator}};
use crate::infrastructure::bus::EnterpriseBus;
use crate::presentation::state::AppState;

{handler_imports}
#[tokio::main]
async fn main() -> Result<()> {{
    // 1. Load .env if present (ignored when absent).
    let _ = dotenvy::dotenv();

    // 2. Load settings (config/default.toml + APP__* env).
    let settings = Settings::load()?;
    info!(project = "{project}", schema = "{schema}", "starting hexagonal REST API");

    // 3. Initialise telemetry (tracing + OpenTelemetry stub + Prometheus stub).
    crate::telemetry::init("hexagonal-rest-api")?;
    crate::logging::init_logging("hexagonal-rest-api")?;

    // 4. Build the PostgreSQL pool.
    info!("connecting to PostgreSQL");
    let pool: PgPool = crate::infrastructure::db::build_pool(
        &settings.database.url,
        settings.database.max_connections,
        settings.database.min_connections,
        settings.database.acquire_timeout_secs,
    )
    .await?;
    info!("connected to PostgreSQL");

    // 5. Run migrations when enabled.
    // v0.4.0 (closes G-H11): resolve the migrations directory against the
    // binary's own location first, then the current working directory, so
    // the binary boots correctly regardless of the CWD it was launched
    // from. The previous `Path::new("migrations")` form broke when the
    // binary was launched from a systemd unit, Docker ENTRYPOINT, or any
    // other non-project-root directory.
    if settings.database.migrate_on_start {{
        info!("running database migrations");
        let migrations_dir = locate_migrations_dir();
        info!(path = %migrations_dir.display(), "migrations directory resolved");
        let migrator = sqlx::migrate::Migrator::new(migrations_dir.as_path())
            .await
            .map_err(|e| {{
                tracing::error!(error = %e, path = %migrations_dir.display(),
                                "failed to load migrator");
                e
            }})?;
        migrator.run(&pool).await.map_err(|e| {{
            tracing::error!(error = %e, "database migration failed");
            e
        }})?;
        info!("database migrations complete");
    }}

    // 6. Wire adapters → services → AppState.
{wiring}
    let bus: Arc<dyn EventBus> = Arc::new(EnterpriseBus::new());
    let inflight = Arc::new(InFlightTracker::new());
    let coordinator = Arc::new(ShutdownCoordinator::new());

    // v0.4.0 (closes G-H01, G-H02): construct the JWT service and RBAC
    // policy. The JWT secret is read from settings; the RBAC policy
    // starts empty (handlers fall back to the `require_role` helper
    // when no policy entries are loaded). In v0.5 the RBAC policy will
    // be loaded from a `rbac_policies` table.
    let jwt = Arc::new(crate::security::auth::jwt::JwtService::new(
        &settings.auth.jwt_secret,
        &settings.auth.issuer,
        &settings.auth.audience,
        settings.auth.ttl_secs as i64,
    ));
    info!(issuer = %settings.auth.issuer, audience = %settings.auth.audience,
          "JWT service constructed");
    let rbac = Arc::new(crate::security::auth::rbac::RbacPolicy::new());
    info!("RBAC policy constructed (empty — populate via policy.add() at boot)");

    let state = AppState {{
        pool: pool.clone(),
{state_fields}        bus,
        inflight: inflight.clone(),
        jwt,
        rbac,
    }};

    // 7. Build the router.
    let api_router = crate::presentation::routes::router();
    let app = crate::presentation::build_router(state);

    // 8. Bind, mark Ready, and serve with ordered graceful shutdown.
    let addr = settings.server.bind_addr();
    info!(addr = %addr, "binding TCP listener");
    let listener = tokio::net::TcpListener::bind(&addr).await?;
    info!(addr = %addr, "service ready");

    axum::serve(listener, app.into_make_service())
        .with_graceful_shutdown({{
            let c = coordinator.clone();
            let inflight_clone = inflight.clone();
            async move {{
                shutdown_signal().await;
                c.shutdown(&inflight_clone).await;
            }}
        }})
        .await?;

    // v1.0.0 (closes G-M18): report whether the drain succeeded or
    // was forced. The previous code logged "shutdown complete"
    // unconditionally, masking dropped inflight requests.
    let remaining = inflight.inflight_count();
    if remaining > 0 {{
        warn!(dropped = remaining,
              "shutdown forced — inflight requests were dropped");
    }} else {{
        info!("shutdown complete — all inflight requests drained");
    }}
    Ok(())
}}

/// Waits for Ctrl+C or SIGTERM, then returns to trigger graceful shutdown.
async fn shutdown_signal() {{
    let ctrl_c = async {{
        tokio::signal::ctrl_c()
            .await
            .expect("failed to install Ctrl+C handler");
    }};

    #[cfg(unix)]
    let terminate = async {{
        tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate())
            .expect("failed to install SIGTERM handler")
            .recv()
            .await;
    }};

    #[cfg(not(unix))]
    let terminate = std::future::pending::<()>();

    tokio::select! {{
        _ = ctrl_c => warn!("received Ctrl+C, shutting down"),
        _ = terminate => warn!("received SIGTERM, shutting down"),
    }}
}}

/// Resolves the migrations directory robustly.
///
/// v0.4.0 (closes G-H11). Tries four candidate locations in order:
/// 1. `$HEX_GEN_MIGRATIONS_DIR` env var (explicit override)
/// 2. `<binary_dir>/migrations` (next to the executable — Docker, systemd)
/// 3. `<cwd>/migrations` (the original v0.3 behaviour, kept for dev)
/// 4. `<binary_dir>/../migrations` (typical multi-stage Docker layout
///    where the binary is at `/app/bin/` and migrations at `/app/migrations/`)
///
/// Returns the first directory that exists; falls back to `cwd/migrations`
/// so the error message stays helpful when nothing is found.
fn locate_migrations_dir() -> std::path::PathBuf {{
    use std::path::PathBuf;

    // 1. Explicit env override.
    if let Ok(p) = std::env::var("HEX_GEN_MIGRATIONS_DIR") {{
        let path = PathBuf::from(p);
        if path.is_dir() {{
            tracing::info!(source = "env", path = %path.display(),
                           "located migrations directory");
            return path;
        }}
        tracing::warn!(path = %path.display(),
                       "HEX_GEN_MIGRATIONS_DIR set but not a directory");
    }}

    // 2 / 4. Relative to the binary.
    if let Ok(exe) = std::env::current_exe() {{
        if let Some(bin_dir) = exe.parent() {{
            let candidate = bin_dir.join("migrations");
            if candidate.is_dir() {{
                tracing::info!(source = "bin_dir", path = %candidate.display(),
                               "located migrations directory");
                return candidate;
            }}
            let candidate = bin_dir.join("..").join("migrations");
            if candidate.is_dir() {{
                tracing::info!(source = "bin_dir_parent", path = %candidate.display(),
                               "located migrations directory");
                return candidate;
            }}
        }}
    }}

    // 3. CWD fallback (dev mode).
    let fallback = PathBuf::from("migrations");
    tracing::warn!(path = %fallback.display(),
                   "migrations directory not found via env or binary location; falling back to CWD");
    fallback
}}
"#,
        project = cfg.project_name,
        schema = schema.schema,
        handler_imports = handler_imports,
        wiring = wiring,
        state_fields = state_fields,
    )
}
