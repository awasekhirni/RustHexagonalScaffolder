/// Renders the Dockerfile with the project's binary name substituted
/// into the `__BIN_NAME__` placeholder. v1.0.0 (closes G-M19).
fn dockerfile(cfg: &Config) -> String {
    let bin_name = cfg.project_name.replace('-', "_");
    DOCKERFILE.replace("__BIN_NAME__", &bin_name)
}

