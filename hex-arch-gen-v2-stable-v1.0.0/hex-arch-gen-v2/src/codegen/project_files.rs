//! Project-level artefacts of the generated application:
//! `Cargo.toml`, `.env`, `.env.example`, `.gitignore`, `config/default.toml`
//! and `README.md`.
//!
//! The `Cargo.toml` is the dependency manifest of the **generated** service,
//! matching the v0.6.0 desired-state platform's dependency set (trimmed to
//! the subset the generated code actually uses, so `cargo check` is fast).

use std::path::Path;

use crate::codegen::write_file;
use crate::config::Config;
use crate::errors::GenResult;
use crate::ir::Schema;

/// Writes all project-level files.
pub fn write_all(schema: &Schema, root: &Path, cfg: &Config) -> GenResult<()> {
    write_file(&root.join("Cargo.toml"), &cargo_toml(cfg))?;
    write_file(&root.join(".env"), &env_file(cfg, false))?;
    write_file(&root.join(".env.example"), &env_file(cfg, true))?;
    write_file(&root.join(".gitignore"), GITIGNORE)?;
    write_file(&root.join("Makefile"), MAKEFILE)?;
    write_file(&root.join("Dockerfile"), &dockerfile(cfg))?;
    write_file(&root.join("docker-compose.yml"), &docker_compose(cfg))?;
    write_file(&root.join("README.md"), &readme(schema, cfg))?;

    // Typed config (config/default.toml) — read by the `config` crate at boot.
    let config_dir = root.join("config");
    write_file(&config_dir.join("default.toml"), &default_toml(cfg))?;

    // v0.4.0 (closes G-H10): GitHub Actions CI matrix + SBOM Makefile
    // target are emitted as static assets so every generated project
    // ships with reproducible CI out of the box.
    let gh_dir = root.join(".github").join("workflows");
    write_file(&gh_dir.join("ci.yml"), CI_YML)?;
    write_file(&gh_dir.join("release.yml"), RELEASE_YML)?;

    Ok(())
}

