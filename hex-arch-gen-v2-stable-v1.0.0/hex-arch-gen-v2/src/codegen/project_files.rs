/// `.env` (real values) or `.env.example` (placeholders).
fn env_file(cfg: &Config, example: bool) -> String {
    if example {
        "DATABASE_URL=postgresql://user:password@localhost:5432/dbname\nAPP__SERVER__BIND_ADDRESS=0.0.0.0:8080\nAPP__DATABASE__MAX_CONNECTIONS=10\nRUST_LOG=info\n".to_string()
    } else {
        format!(
            "DATABASE_URL={url}\nAPP__SERVER__BIND_ADDRESS=0.0.0.0:8080\nAPP__DATABASE__MAX_CONNECTIONS=10\nRUST_LOG=info\n",
            url = cfg.database_url
        )
    }
}

