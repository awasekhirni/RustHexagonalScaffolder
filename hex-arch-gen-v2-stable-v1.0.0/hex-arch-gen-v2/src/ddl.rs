//! DDL/migration SQL generation.
//!
//! Produces a single `migrations/<timestamp>_init_schema.sql` file
//! capturing every table, enum, and index from the IR. The output is
//! idempotent (`CREATE TYPE … AS ENUM`, `CREATE TABLE …`, `CREATE INDEX …`)
//! and round-trips through the introspector.
//!
//! v1.0.0 (closes G-M05): the migration now includes a commented
//! `-- DOWN:` section at the bottom with `DROP TABLE IF EXISTS ...`
//! and `DROP TYPE IF EXISTS ...` statements in reverse dependency
//! order, so operators can roll back by running the DOWN section.
//! The UP section (the existing CREATE statements) is unchanged.
//!
//! # Why a single migration?
//!
//! The generator is db-first: the introspector is the source of truth, so
//! there is no evolution story to capture. Users who want to evolve the
//! schema edit the SQL directly and re-run the introspector.
//!
//! # Compatibility
//!
//! The emitted SQL targets PostgreSQL 13+ (uses `gen_random_uuid()` from
//! `pgcrypto`/`pg_catalog` for UUID PK defaults).

use crate::codegen::write_file;
use crate::errors::GenResult;
use crate::ir::Schema;
use std::path::Path;

/// Writes the DDL migration file under `<root>/migrations/`.
///
/// # Errors
///
/// Surfaces [`crate::errors::GenError::Io`] on filesystem failures.
pub fn write_migration(schema: &Schema, root: &Path) -> GenResult<()> {
    let migrations_dir = root.join("migrations");
    let path = migrations_dir.join("20240101000001_init_schema.sql");
    write_file(&path, &render(schema))?;
    Ok(())
}

/// Renders the SQL migration as a single string.
fn render(schema: &Schema) -> String {
    let mut out = String::new();

    out.push_str("-- Generated by hex-gen v2 (db-first DDL regeneration).\n");
    out.push_str("-- Schema: ");
    out.push_str(&schema.schema);
    out.push_str("\n--\n-- This migration captures the introspected schema as a single\n");
    out.push_str(
        "-- idempotent snapshot. Apply with `psql $DATABASE_URL -f migrations/*.sql`.\n\n",
    );

    // ── enums ─────────────────────────────────────────────────────────────
    if !schema.enums.is_empty() {
        out.push_str("-- ── native PostgreSQL enums ──────────────────────────────────────\n");
        for (pg_name, labels) in &schema.enums {
            out.push_str(&format!(
                "CREATE TYPE {} AS ENUM ({});\n",
                pg_name,
                labels
                    .iter()
                    .map(|l| format!("'{l}'"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        out.push('\n');
    }

    // ── tables ────────────────────────────────────────────────────────────
    out.push_str("-- ── tables ───────────────────────────────────────────────────────\n");
    for table in &schema.tables {
        out.push_str(&render_table(table));
        out.push('\n');
    }

    // ── indexes ───────────────────────────────────────────────────────────
    if !schema.indexes.is_empty() {
        out.push_str("-- ── secondary indexes ────────────────────────────────────────────\n");
        for idx in &schema.indexes {
            let unique = if idx.unique { "UNIQUE " } else { "" };
            out.push_str(&format!(
                "CREATE {unique}INDEX {} ON {} ({});\n",
                idx.name,
                idx.table,
                idx.columns.join(", ")
            ));
        }
    }

    // v1.0.0 (closes G-M05): DOWN section — DROP statements in reverse
    // dependency order (indexes first, then tables, then enums) so
    // operators can roll back by running this section.
    out.push_str("\n-- ── DOWN (rollback) ─────────────────────────────────────────────\n");
    out.push_str("-- Run this section to roll back the migration.\n");
    out.push_str("-- Indexes first, then tables (in reverse FK-dependency order), then enums.\n\n");
    // Drop indexes.
    for idx in &schema.indexes {
        out.push_str(&format!("DROP INDEX IF EXISTS {};\n", idx.name));
    }
    // Drop tables in reverse order (FK children before parents).
    for table in schema.tables.iter().rev() {
        out.push_str(&format!("DROP TABLE IF EXISTS {};\n", table.name));
    }
    // Drop enums.
    for (pg_name, _) in &schema.enums {
        out.push_str(&format!("DROP TYPE IF EXISTS {};\n", pg_name));
    }

    out
}

/// Renders a single `CREATE TABLE` statement.
fn render_table(table: &crate::ir::Table) -> String {
    let mut out = format!("CREATE TABLE {} (\n", table.name);

    let mut col_lines = Vec::new();
    for col in &table.columns {
        col_lines.push(format!("    {} {}", col.name, sql_type(&col.kind)));
    }

    // PK constraint
    if let Some(pk) = table.pk() {
        col_lines.push(format!("    PRIMARY KEY ({})", pk.name));
    }

    // FK constraints
    for fk in &table.foreign_keys {
        col_lines.push(format!(
            "    FOREIGN KEY ({}) REFERENCES {} ({})",
            fk.column, fk.ref_table, fk.ref_column
        ));
    }

    out.push_str(&col_lines.join(",\n"));
    out.push_str("\n);\n");
    out
}

/// Returns the PostgreSQL type for a [`crate::ir::ColKind`] (the inverse of
/// the introspector's `resolve_kind`).
fn sql_type(kind: &crate::ir::ColKind) -> String {
    match kind {
        crate::ir::ColKind::Str => "text".into(),
        crate::ir::ColKind::I16 => "int2".into(),
        crate::ir::ColKind::I32 => "int4".into(),
        crate::ir::ColKind::I64 => "int8".into(),
        crate::ir::ColKind::F32 => "float4".into(),
        crate::ir::ColKind::F64 => "float8".into(),
        crate::ir::ColKind::Bool => "boolean".into(),
        crate::ir::ColKind::Uuid => "uuid".into(),
        crate::ir::ColKind::NaiveDate => "date".into(),
        crate::ir::ColKind::NaiveTime => "time".into(),
        crate::ir::ColKind::NaiveDateTime => "timestamp".into(),
        crate::ir::ColKind::DateTimeUtc => "timestamptz".into(),
        crate::ir::ColKind::Json => "jsonb".into(),
        crate::ir::ColKind::Decimal => "numeric".into(),
        crate::ir::ColKind::Bytes => "bytea".into(),
        crate::ir::ColKind::VecOf(inner) => format!("{}[]", sql_type(inner)),
        crate::ir::ColKind::PgEnum { pg_name, .. } => pg_name.clone(),
        crate::ir::ColKind::Unknown(udt) => udt.clone(),
        // v1.0.0 (closes G-M01): extended types.
        crate::ir::ColKind::Interval => "interval".into(),
        crate::ir::ColKind::BitString => "bytea".into(),
        crate::ir::ColKind::Ltree => "text".into(),
        crate::ir::ColKind::TsVector => "tsvector".into(),
        crate::ir::ColKind::Hstore => "jsonb".into(),
        crate::ir::ColKind::Macaddr => "macaddr".into(),
        crate::ir::ColKind::Macaddr8 => "macaddr8".into(),
        crate::ir::ColKind::Cidr => "cidr".into(),
        crate::ir::ColKind::Inet => "inet".into(),
    }
}
