//! Domain layer codegen — the hexagon core for each table:
//! entity, input models, native-PG-enum types, repository port, service port.

use std::path::Path;

use anyhow::Result;
use heck::ToUpperCamelCase;

use crate::codegen::{write_file, ImportSet};
use crate::ir::{ColKind, Schema, Table};

/// Writes `src/domain/<table>/` for one table.
pub fn write_table(schema: &Schema, root: &Path, t: &Table) -> Result<()> {
    let dir = root.join("src").join("domain").join(&t.module_name);

    write_file(&dir.join("entity.rs"), &entity_rs(t))?;
    write_file(&dir.join("input.rs"), &input_rs(t))?;
    if !t.used_enums().is_empty() {
        write_file(&dir.join("enums.rs"), &enums_rs(t, schema))?;
    }
    write_file(&dir.join("repository.rs"), &repository_port_rs(t))?;
    write_file(&dir.join("service.rs"), &service_port_rs(t))?;
    write_file(&dir.join("mod.rs"), &table_mod_rs(t))?;
    Ok(())
}

/// Writes `src/domain/mod.rs` listing every bounded context.
pub fn write_mod(schema: &Schema, root: &Path) -> Result<()> {
    let mut body = String::from("//! Domain layer — entities, input models and ports (the hexagon core).\n//!\n//! This layer knows nothing about axum, SQLx or HTTP: it only declares\n//! *what* the application can do, never *how* it is done.\n\n");
    for t in &schema.tables {
        body.push_str(&format!("pub mod {};\n", t.module_name));
    }
    write_file(&root.join("src").join("domain").join("mod.rs"), &body)
}

// ─────────────────────────────────────────────────────────────────────────────
// entity.rs
// ─────────────────────────────────────────────────────────────────────────────

fn entity_rs(t: &Table) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "//! Domain entity for the `{}` table.\n//!\n//! Generated by `hex-gen`. Maps 1:1 to the PostgreSQL table via\n//! [`sqlx::FromRow`]; serializes to JSON for both HTTP responses and the\n//! OpenAPI document (utoipa).\n\n",
        t.name
    ));

    let imports = ImportSet::from_cols(t.columns.iter());
    for line in imports.render() {
        out.push_str(&line);
        out.push('\n');
    }
    out.push_str("use serde::{Deserialize, Serialize};\n");
    out.push_str("use sqlx::FromRow;\n");
    out.push_str("use utoipa::ToSchema;\n");
    for (_, rust_name) in t.used_enums() {
        out.push_str(&format!(
            "use crate::domain::{}::enums::{};\n",
            t.module_name, rust_name
        ));
    }

    out.push_str(&format!(
        "\n/// Aggregate root for `{}` records (PostgreSQL table `{}`).\n#[derive(Debug, Clone, Default, Serialize, Deserialize, FromRow, ToSchema)]\npub struct {} {{\n",
        t.name, t.name, t.struct_name
    ));
    for c in &t.columns {
        let mut doc = c.doc_line();
        if let Some(fk) = t.foreign_keys.iter().find(|f| f.column == c.name) {
            doc.push_str(&format!(
                " References `{}({})`.",
                fk.ref_table, fk.ref_column
            ));
        }
        out.push_str(&format!("    /// {doc}\n"));
        if let Some(attr) = c.schema_attr() {
            out.push_str(&format!("    {attr}\n"));
        }
        for attr in c.rename_attrs() {
            out.push_str(&format!("    {attr}\n"));
        }
        out.push_str(&format!("    pub {}: {},\n", c.field_ident, c.entity_type()));
    }
    out.push_str("}\n\n");

    out.push_str(&format!(
        "impl {} {{\n    /// Placeholder for domain invariants; the application service\n    /// calls this before every write. Replace with real rules.\n    pub fn validate(&self) -> Result<(), String> {{\n        Ok(())\n    }}\n}}\n",
        t.struct_name
    ));
    out
}

// ─────────────────────────────────────────────────────────────────────────────
// input.rs — Create/Update payload models (double as validation boundary)
// ─────────────────────────────────────────────────────────────────────────────

fn input_rs(t: &Table) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "//! Write-side input models for `{}`.\n//!\n//! `Create{0}Input` covers every client-writable column of an INSERT\n//! (server-generated columns are filled by the database); `Update{0}Input`\n//! is fully optional so `PUT` behaves as a partial update.\n\n",
        t.struct_name
    ));

    let imports = ImportSet::from_cols(t.insert_cols().into_iter().chain(t.update_cols()));
    for line in imports.render() {
        out.push_str(&line);
        out.push('\n');
    }
    out.push_str("use serde::Deserialize;\n");
    out.push_str("use utoipa::ToSchema;\n");
    for (_, rust_name) in t.used_enums() {
        out.push_str(&format!(
            "use crate::domain::{}::enums::{};\n",
            t.module_name, rust_name
        ));
    }

    // Create input
    let insert_cols = t.insert_cols();
    out.push_str(&format!(
        "\n/// Payload accepted by `POST /{}` — validated before persistence.\n#[derive(Debug, Clone, Deserialize, ToSchema)]\npub struct Create{}Input {{\n",
        t.module_name, t.struct_name
    ));
    for c in &insert_cols {
        out.push_str(&format!("    /// {}\n", c.doc_line()));
        if let Some(attr) = c.schema_attr() {
            out.push_str(&format!("    {attr}\n"));
        }
        if let Some(attr) = c.serde_rename() {
            out.push_str(&format!("    {attr}\n"));
        }
        out.push_str(&format!("    pub {}: {},\n", c.field_ident, c.create_type()));
    }
    out.push_str("}\n\n");

    // validate(): guard every required String field
    out.push_str(&format!(
        "impl Create{}Input {{\n    /// Bean-style validation invoked by the application service.\n    /// Extend here (or in the entity) with real business rules.\n    pub fn validate(&self) -> Result<(), String> {{\n",
        t.struct_name
    ));
    for c in insert_cols
        .iter()
        .filter(|c| !c.nullable && matches!(c.kind, ColKind::Str))
    {
        out.push_str(&format!(
            "        if self.{}.trim().is_empty() {{\n            return Err(\"{} must not be empty\".to_string());\n        }}\n",
            c.field_ident, c.name
        ));
    }
    out.push_str("        Ok(())\n    }\n}\n\n");

    // Update input
    out.push_str(&format!(
        "/// Payload accepted by `PUT /{}/{{id}}` — every field optional.\n#[derive(Debug, Clone, Default, Deserialize, ToSchema)]\npub struct Update{}Input {{\n",
        t.module_name, t.struct_name
    ));
    for c in t.update_cols() {
        out.push_str(&format!("    /// Optional new value for `{}`.\n", c.name));
        if let Some(attr) = c.schema_attr() {
            out.push_str(&format!("    {attr}\n"));
        }
        if let Some(attr) = c.serde_rename() {
            out.push_str(&format!("    {attr}\n"));
        }
        out.push_str(&format!("    pub {}: {},\n", c.field_ident, c.update_type()));
    }
    out.push_str("}\n");
    out
}

// ─────────────────────────────────────────────────────────────────────────────
// enums.rs — native PostgreSQL enums as first-class Rust types
// ─────────────────────────────────────────────────────────────────────────────

fn enums_rs(t: &Table, schema: &Schema) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "//! Native PostgreSQL enum types used by the `{}` table.\n//!\n//! Generated enums map to the database types through\n//! `#[sqlx(type_name = …, rename_all = \"snake_case\")]` and to JSON through\n//! serde with the identical casing, so labels round-trip losslessly.\n\n",
        t.name
    ));
    out.push_str("use serde::{Deserialize, Serialize};\n");
    out.push_str("use sqlx::Type;\n");
    out.push_str("use utoipa::ToSchema;\n");

    for (pg_name, rust_name) in t.used_enums() {
        let labels = schema
            .enums
            .get(&pg_name)
            .cloned()
            .unwrap_or_default();

        out.push_str(&format!(
            "\n/// Native PostgreSQL enum `{pg_name}` (labels: {}).\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize, Type, ToSchema)]\n#[sqlx(type_name = \"{pg_name}\", rename_all = \"snake_case\")]\n#[serde(rename_all = \"snake_case\")]\npub enum {rust_name} {{\n",
            labels.join(", ")
        ));
        for (idx, label) in labels.iter().enumerate() {
            out.push_str(&format!("    /// `{label}`\n"));
            if idx == 0 {
                out.push_str("    #[default]\n");
            }
            out.push_str(&format!("    {},\n", variant_ident(label)));
        }
        out.push_str("}\n\n");

        out.push_str(&format!(
            "impl std::str::FromStr for {rust_name} {{\n    type Err = String;\n\n    /// Parses a raw string (e.g. a path segment) into the enum.\n    fn from_str(raw: &str) -> Result<Self, Self::Err> {{\n        match raw {{\n"
        ));
        for label in &labels {
            out.push_str(&format!(
                "            \"{label}\" => Ok(Self::{}),\n",
                variant_ident(label)
            ));
        }
        out.push_str(&format!(
            "            other => Err(format!(\"unknown {pg_name} value: {{other}}\")),\n        }}\n    }}\n}}\n"
        ));
    }
    out
}

/// Rust variant identifier for a PG enum label.
fn variant_ident(label: &str) -> String {
    label.to_upper_camel_case().replace(['-', ' '], "_")
}

// ─────────────────────────────────────────────────────────────────────────────
// repository.rs / service.rs — the ports
// ─────────────────────────────────────────────────────────────────────────────

/// Rust type used to *name* a status value in ports and handlers.
pub fn status_type(t: &Table) -> Option<String> {
    let col = t
        .columns
        .iter()
        .find(|c| Some(&c.name) == t.analysis.status_col.as_ref())?;
    Some(match &col.kind {
        ColKind::PgEnum { rust_name, .. } => rust_name.clone(),
        _ => "String".to_string(),
    })
}

/// Rust type of the user-reference column, when present.
pub fn user_type(t: &Table) -> Option<String> {
    let col = t
        .columns
        .iter()
        .find(|c| Some(&c.name) == t.analysis.user_col.as_ref())?;
    Some(col.kind.rust_type())
}

/// Rust type of a timestamp feature column (`created_at`/`updated_at`).
pub fn ts_type(t: &Table, which: &Option<String>) -> Option<String> {
    let col = t.columns.iter().find(|c| Some(&c.name) == which.as_ref())?;
    Some(col.kind.rust_type())
}

/// Columns referenced by port signatures (for import calculation).
pub fn port_feature_cols(t: &Table) -> Vec<&crate::ir::Column> {
    let mut cols = Vec::new();
    for name in [
        t.analysis.status_col.as_ref(),
        t.analysis.deleted_at_col.as_ref(),
        t.analysis.user_col.as_ref(),
        t.analysis.created_at_col.as_ref(),
        t.analysis.updated_at_col.as_ref(),
    ]
    .into_iter()
    .flatten()
    {
        if let Some(c) = t.columns.iter().find(|c| &c.name == name) {
            cols.push(c);
        }
    }
    cols
}

fn repository_port_rs(t: &Table) -> String {
    let pk = t.pk().expect("pk required for codegen");
    let mut out = String::new();
    out.push_str(&format!(
        "//! Outbound port — repository contract for `{}`.\n//!\n//! Owned by the domain layer, implemented by `infrastructure` with SQLx.\n\n",
        t.name
    ));
    out.push_str("use async_trait::async_trait;\n");
    let mut scan_cols: Vec<&crate::ir::Column> = vec![pk];
    scan_cols.extend(port_feature_cols(t));
    for line in ImportSet::from_cols(scan_cols).render() {
        out.push_str(&line);
        out.push('\n');
    }
    out.push_str(&format!(
        "use crate::domain::{}::entity::{};\nuse crate::enterprise::repository::{{Page, Repository, RepositoryError}};\n",
        t.module_name, t.struct_name
    ));
    for (_, rust_name) in t.used_enums() {
        out.push_str(&format!(
            "use crate::domain::{}::enums::{};\n",
            t.module_name, rust_name
        ));
    }

    out.push_str(&format!(
        "\n/// Repository port for `{}` — extends the enterprise base repository\n/// with the context-specific look-ups detected in the schema.\n#[async_trait]\npub trait {}Repository: Repository<{}, {}> {{\n",
        t.name, t.struct_name, t.struct_name, pk.kind.rust_type()
    ));

    if let Some(status) = status_type(t) {
        out.push_str(&format!(
            "    /// Lists records sharing a status value.\n    async fn find_by_status(&self, status: {status}, page: Page) -> Result<Vec<{}>, RepositoryError>;\n",
            t.struct_name
        ));
        out.push_str(&format!(
            "    /// Updates the status column of one record.\n    async fn set_status(&self, id: {}, status: {status}) -> Result<Option<{}>, RepositoryError>;\n",
            pk.kind.rust_type(),
            t.struct_name
        ));
    }
    if t.analysis.soft_flag_col.is_some() || t.analysis.deleted_at_col.is_some() {
        out.push_str(&format!(
            "    /// Tombstones the record (soft delete) instead of removing it.\n    async fn soft_delete(&self, id: {}) -> Result<bool, RepositoryError>;\n",
            pk.kind.rust_type()
        ));
        out.push_str(&format!(
            "    /// Restores a soft-deleted record and returns it.\n    async fn restore(&self, id: {}) -> Result<Option<{}>, RepositoryError>;\n",
            pk.kind.rust_type(),
            t.struct_name
        ));
    }
    if let Some(user) = user_type(t) {
        out.push_str(&format!(
            "    /// Lists records belonging to a user.\n    async fn find_by_user(&self, user_id: {user}, page: Page) -> Result<Vec<{}>, RepositoryError>;\n",
            t.struct_name
        ));
    }
    if let Some(ts) = ts_type(t, &t.analysis.created_at_col) {
        out.push_str(&format!(
            "    /// Lists records created at or after `ts`.\n    async fn find_created_after(&self, ts: {ts}, page: Page) -> Result<Vec<{}>, RepositoryError>;\n",
            t.struct_name
        ));
    }
    if let Some(ts) = ts_type(t, &t.analysis.updated_at_col) {
        out.push_str(&format!(
            "    /// Lists records updated at or after `ts`.\n    async fn find_updated_after(&self, ts: {ts}, page: Page) -> Result<Vec<{}>, RepositoryError>;\n",
            t.struct_name
        ));
    }
    out.push_str("}\n");
    out
}

fn service_port_rs(t: &Table) -> String {
    let pk = t.pk().expect("pk required for codegen");
    let mut out = String::new();
    out.push_str(&format!(
        "//! Inbound port — application service contract for `{}`.\n//!\n//! HTTP handlers reach this use-case through the enterprise bus; nothing\n//! above this trait knows about SQLx or PostgreSQL.\n\n",
        t.name
    ));
    out.push_str("use async_trait::async_trait;\n");
    let mut scan_cols: Vec<&crate::ir::Column> = vec![pk];
    scan_cols.extend(port_feature_cols(t));
    for line in ImportSet::from_cols(scan_cols).render() {
        out.push_str(&line);
        out.push('\n');
    }
    out.push_str(&format!(
        "use crate::domain::{0}::entity::{1};\nuse crate::domain::{0}::input::{{Create{1}Input, Update{1}Input}};\nuse crate::enterprise::repository::{{Page, Paginated, RepositoryError}};\n",
        t.module_name, t.struct_name
    ));
    for (_, rust_name) in t.used_enums() {
        out.push_str(&format!(
            "use crate::domain::{}::enums::{};\n",
            t.module_name, rust_name
        ));
    }

    out.push_str(&format!(
        "\n/// Application service contract for `{}`.\n#[async_trait]\npub trait {}Service: Send + Sync {{\n    /// Fetches one record by primary key.\n    async fn get(&self, id: {}) -> Result<Option<{}>, RepositoryError>;\n    /// Lists records page by page.\n    async fn list(&self, page: Page) -> Result<Paginated<{}>, RepositoryError>;\n    /// Validates and persists a new record.\n    async fn create(&self, input: Create{}Input) -> Result<{}, RepositoryError>;\n    /// Applies a partial update; `None` when the record is missing.\n    async fn update(&self, id: {}, input: Update{}Input) -> Result<Option<{}>, RepositoryError>;\n    /// Deletes a record (hard delete when soft delete is unavailable).\n    async fn delete(&self, id: {}) -> Result<bool, RepositoryError>;\n",
        t.name,
        t.struct_name,
        pk.kind.rust_type(),
        t.struct_name,
        t.struct_name,
        t.struct_name,
        t.struct_name,
        pk.kind.rust_type(),
        t.struct_name,
        t.struct_name,
        pk.kind.rust_type()
    ));

    if let Some(status) = status_type(t) {
        out.push_str(&format!(
            "    /// Lists records by status.\n    async fn list_by_status(&self, status: {status}, page: Page) -> Result<Vec<{}>, RepositoryError>;\n    /// Changes the status of one record.\n    async fn set_status(&self, id: {}, status: {status}) -> Result<Option<{}>, RepositoryError>;\n",
            t.struct_name, pk.kind.rust_type(), t.struct_name
        ));
    }
    if t.analysis.soft_flag_col.is_some() || t.analysis.deleted_at_col.is_some() {
        out.push_str(&format!(
            "    /// Soft-deletes a record.\n    async fn soft_delete(&self, id: {}) -> Result<bool, RepositoryError>;\n    /// Restores a soft-deleted record.\n    async fn restore(&self, id: {}) -> Result<Option<{}>, RepositoryError>;\n",
            pk.kind.rust_type(),
            pk.kind.rust_type(),
            t.struct_name
        ));
    }
    if let Some(user) = user_type(t) {
        out.push_str(&format!(
            "    /// Lists records belonging to a user.\n    async fn list_by_user(&self, user_id: {user}, page: Page) -> Result<Vec<{}>, RepositoryError>;\n",
            t.struct_name
        ));
    }
    if let Some(ts) = ts_type(t, &t.analysis.created_at_col) {
        out.push_str(&format!(
            "    /// Lists records created at or after `ts`.\n    async fn list_created_after(&self, ts: {ts}, page: Page) -> Result<Vec<{}>, RepositoryError>;\n",
            t.struct_name
        ));
    }
    if let Some(ts) = ts_type(t, &t.analysis.updated_at_col) {
        out.push_str(&format!(
            "    /// Lists records updated at or after `ts`.\n    async fn list_updated_after(&self, ts: {ts}, page: Page) -> Result<Vec<{}>, RepositoryError>;\n",
            t.struct_name
        ));
    }
    out.push_str("}\n");
    out
}

fn table_mod_rs(t: &Table) -> String {
    let mut body = format!(
        "//! Domain context for `{}` — entity, inputs and ports.\n\npub mod entity;\n",
        t.name
    );
    if !t.used_enums().is_empty() {
        body.push_str("pub mod enums;\n");
    }
    body.push_str("pub mod input;\n");
    body.push_str("pub mod repository;\n");
    body.push_str("pub mod service;\n");
    body
}
