//! Generated `main.rs` — axum bootstrap, PostgreSQL pool and the wiring
//! of repositories → services → enterprise-bus handlers.

use std::path::Path;

use anyhow::Result;

use crate::codegen::write_file;
use crate::config::Config;
use crate::ir::Schema;

/// Writes `src/main.rs` of the generated project.
pub fn write(schema: &Schema, root: &Path, cfg: &Config) -> Result<()> {
    let mut handler_imports = String::new();
    let mut wiring = String::new();

    for t in &schema.tables {
        let m = &t.module_name;
        let n = &t.struct_name;

        // ── imports for main.rs ─────────────────────────────────────────────────
        handler_imports.push_str(&format!(
            "use crate::application::{m}_messaging::{{{n}Handlers, Create{n}Command, Delete{n}Command, Get{n}Query, List{n}Query, Update{n}Command",
        ));
        if t.analysis.status_col.is_some() {
            handler_imports.push_str(&format!(
                ", List{n}ByStatusQuery, Set{n}StatusCommand"
            ));
        }
        if t.analysis.soft_flag_col.is_some() || t.analysis.deleted_at_col.is_some() {
            handler_imports.push_str(&format!(
                ", Restore{n}Command, SoftDelete{n}Command"
            ));
        }
        if t.analysis.user_col.is_some() {
            handler_imports.push_str(&format!(", List{n}ByUserQuery"));
        }
        if t.analysis.created_at_col.is_some() {
            handler_imports.push_str(&format!(", List{n}CreatedAfterQuery"));
        }
        if t.analysis.updated_at_col.is_some() {
            handler_imports.push_str(&format!(", List{n}UpdatedAfterQuery"));
        }
        handler_imports.push_str("};\n");
        handler_imports.push_str(&format!(
            "use crate::application::{m}_service::{n}ServiceImpl;\nuse crate::domain::{m}::service::{n}Service;\nuse crate::infrastructure::{m}_repository::Postgres{n}Repository;\n"
        ));

        // ── construction + bus registration ─────────────────────────────
        wiring.push_str(&format!(
            "\n    // ── {m} context ────────────────────────────────────────────────────\n    let {m}_repo = std::sync::Arc::new(Postgres{n}Repository::new(pool.clone()));\n    let {m}_service: std::sync::Arc<dyn {n}Service> = std::sync::Arc::new({n}ServiceImpl::new({m}_repo));\n    let {m}_handlers = {n}Handlers::new({m}_service);\n\n    cmd_bus.register::<Create{n}Command, _>({m}_handlers.clone());\n    cmd_bus.register::<Update{n}Command, _>({m}_handlers.clone());\n    cmd_bus.register::<Delete{n}Command, _>({m}_handlers.clone());\n"
        ));
        if t.analysis.status_col.is_some() {
            wiring.push_str(&format!(
                "    cmd_bus.register::<Set{n}StatusCommand, _>({m}_handlers.clone());\n"
            ));
        }
        if t.analysis.soft_flag_col.is_some() || t.analysis.deleted_at_col.is_some() {
            wiring.push_str(&format!(
                "    cmd_bus.register::<SoftDelete{n}Command, _>({m}_handlers.clone());\n    cmd_bus.register::<Restore{n}Command, _>({m}_handlers.clone());\n"
            ));
        }
        wiring.push_str(&format!(
            "\n    qry_bus.register::<Get{n}Query, _>({m}_handlers.clone());\n    qry_bus.register::<List{n}Query, _>({m}_handlers.clone());\n"
        ));
        if t.analysis.status_col.is_some() {
            wiring.push_str(&format!(
                "    qry_bus.register::<List{n}ByStatusQuery, _>({m}_handlers.clone());\n"
            ));
        }
        if t.analysis.user_col.is_some() {
            wiring.push_str(&format!(
                "    qry_bus.register::<List{n}ByUserQuery, _>({m}_handlers.clone());\n"
            ));
        }
        if t.analysis.created_at_col.is_some() {
            wiring.push_str(&format!(
                "    qry_bus.register::<List{n}CreatedAfterQuery, _>({m}_handlers.clone());\n"
            ));
        }
        if t.analysis.updated_at_col.is_some() {
            wiring.push_str(&format!(
                "    qry_bus.register::<List{n}UpdatedAfterQuery, _>({m}_handlers.clone());\n"
            ));
        }
    }

    write_file(
        &root.join("src").join("main.rs"),
        &format!(
            r#"//! Bootstraps the generated hexagonal REST API.
//!
//! Wiring direction (hexagonal rules):
//!   HTTP handlers → enterprise buses → application services → domain ports
//!                                                      ↑
//!                                      PostgreSQL adapters (SQLx)
//!
//! Generated by `hex-gen` for schema `{schema}` — edit the generator
//! templates rather than this file.

mod api;
mod application;
mod config;
mod domain;
mod enterprise;
mod error;
mod infrastructure;

use std::time::Duration;

use anyhow::Result;
use axum::Router;
use sqlx::postgres::PgPoolOptions;
use utoipa::OpenApi;
use utoipa_swagger_ui::SwaggerUi;

use crate::api::openapi::ApiDoc;
use crate::api::routes;
use crate::api::state::AppState;
use crate::config::Config;
use crate::enterprise::bus::{{CommandBus, QueryBus}};
{handler_imports}
#[tokio::main]
async fn main() -> Result<()> {{
    dotenvy::dotenv().ok();
    tracing_subscriber::fmt()
        .with_env_filter(tracing_subscriber::EnvFilter::from_default_env())
        .init();

    let config = Config::from_env()?;
    let pool = PgPoolOptions::new()
        .max_connections(config.db_max_connections)
        .acquire_timeout(Duration::from_secs(15))
        .connect(&config.database_url)
        .await?;
    tracing::info!("connected to PostgreSQL (schema: {schema})");

    // ── enterprise buses ────────────────────────────────────────────────────
    let mut cmd_bus = CommandBus::new();
    let mut qry_bus = QueryBus::new();
{wiring}
    let state = AppState {{
        cmd: std::sync::Arc::new(cmd_bus),
        qry: std::sync::Arc::new(qry_bus),
    }};

    // ── HTTP surface ─────────────────────────────────────────────────────────
    let api_router = routes::router().with_state(state);
    let app = Router::new()
        .merge(
            SwaggerUi::new("/swagger-ui")
                .url("/api-docs/openapi.json", ApiDoc::openapi()),
        )
        .nest("/api/v1", api_router);

    let listener = tokio::net::TcpListener::bind(&config.bind_address).await?;
    tracing::info!("HTTP server listening on http://{{}}", config.bind_address);
    tracing::info!("Swagger UI at http://{{}}/swagger-ui", config.bind_address);
    axum::serve(listener, app).await?;
    Ok(())
}}
"#,
            schema = schema.schema,
            handler_imports = handler_imports,
            wiring = wiring,
        ),
    )?;
    let _ = cfg;
    Ok(())
}
